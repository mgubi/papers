def discovery():
    objs = []
    for obj_id, d, inv in objects():
        prov = json.loads(read_logical(d, inv, "provenance.json").read_text())
        objs.append({"id": obj_id, "kind": prov["kind"], "head": inv["head"],
                     "inventorySha512": (d / "inventory.json.sha512").read_text().split()[0],
                     "status": prov["status"]})
    return {"format": "opensheaf-archive/0.1", "specification": SPEC,
            "archiveId": ARCHIVE["archiveId"], "name": ARCHIVE["name"],
            "contact": ARCHIVE["contact"], "storageRoot": "ocfl/", "storageLayout": LAYOUT,
            "mainCollection": ARCHIVE["mainCollection"], "profiles": ARCHIVE["profiles"],
            "objects": objs}


def index_entry(member):
    obj_id, ver = member["id"], member["version"]
    d = OCFL / obj_id
    inv = load_inventory(d)
    prov = json.loads(read_logical(d, inv, "provenance.json", ver).read_text())
    dc = json.loads(read_logical(d, inv, "datacite.json", ver).read_text())
    src = f"ocfl/{obj_id}/" + content_path(inv, ver, prov["mainSource"])
    pdf = f"ocfl/{obj_id}/" + content_path(inv, ver, "paper.pdf")
    html = f"site/{obj_id}/{obj_id}.html"
    title = tm_title(ROOT / src) or dc["titles"][0]["title"]
    authors = ", ".join(display_name(c) for c in dc["creators"])
    related = ""
    for r in dc.get("relatedIdentifiers", []):
        if r["relatedIdentifierType"] == "arXiv":
            a = r["relatedIdentifier"].split(":", 1)[1]
            related = f" See also <hlink|arXiv:{a}|https://arxiv.org/abs/{a}>."
    abstract = ""
    paras = tm_abstract(ROOT / src)
    if paras:
        # a fold in TeXmacs, a details element in HTML (the exporter has no
        # rendering of folded text)
        body = "\n\n".join(f"        {p}" for p in paras)
        abstract = ("    <specific|texmacs|<\\folded>\n      Abstract\n    <|folded>\n"
                    f"{body}\n    </folded>>"
                    "<specific|html*|<html-tag|details|<html-tag|summary|Abstract>"
                    f"<\\html-div-class|paper-abstract>\n{body}\n    </html-div-class>>>\n\n")
    date = datetime.date.fromisoformat(prov["deposit"]["date"][:10])
    day = f"{date.day} {date.strftime('%B %Y')}"
    pin = member["inventorySha512"]
    # Links to .tm files become .html links in the HTML export; the source is
    # linked once for TeXmacs and once (as .texmacs, exported as .tm) for HTML.
    return f"""  <\\notes-news-item>
    <with|font-series|bold|<specific|texmacs|<hlink|{title}|{src}>><specific|html*|<hlink|{title}|{html}>>>

    By {authors}.{related}

    <hlink|HTML|{html}> \\<cdot\\> <hlink|PDF|{pdf}> \\<cdot\\>
    <specific|texmacs|<hlink|TeXmacs source|{src}>><specific|html*|<hlink|TeXmacs
    source|{src[:-3]}.texmacs>>

{abstract}    <with|font-size|0.84|par-mode|left|version {prov['documentVersion']}, deposited
    {day}<next-line>pin: <hlink|<verbatim|{pin[:32]}...>|ocfl/{obj_id}/{ver}/inventory.json>>
  </notes-news-item>"""


def index(args):
    write_json(ROOT / "opensheaf.json", discovery())
    coll_dir = OCFL / ARCHIVE["mainCollection"]
    inv = load_inventory(coll_dir)
    members = json.loads(read_logical(coll_dir, inv, "members.json").read_text())["members"]
    template = (ROOT / "index-template.tm").read_text(encoding="latin-1")
    line = "  <paper-index>\n"
    if template.count(line) != 1:
        sys.exit("index-template.tm must contain one paragraph <paper-index>")
    entries = "\n\n".join(index_entry(m) for m in members)
    with open(ROOT / "index.tm", "w", encoding="latin-1", newline="") as f:
        f.write(template.replace(line, entries + "\n"))
    (ROOT / ".texmacs-noconvert").touch()
    if not args.no_html:
        scratch = Path(tempfile.mkdtemp())
        run_texmacs(export_calls(ROOT / "index.tm", pdf=scratch / "index.pdf",
                                 html=ROOT / "index.html"))
        shutil.rmtree(scratch, ignore_errors=True)
    print("opensheaf.json, index.tm" + ("" if args.no_html else " and index.html") + " written")


