def document_heads():
    out = []
    for obj_id, d, inv in objects():
        prov = json.loads(read_logical(d, inv, "provenance.json").read_text())
        if prov["kind"] == "document":
            dc = json.loads(read_logical(d, inv, "datacite.json").read_text())
            out.append((obj_id, d, inv, prov, dc))
    return out


def collect(args):
    init_storage_root()
    coll_id = ARCHIVE["mainCollection"]
    docs = document_heads()
    docs.sort(key=lambda t: (t[3]["deposit"]["date"], t[0]), reverse=True)
    members = [{
        "kind": "document",
        "archive": ARCHIVE["archiveId"],
        "archiveUrl": ARCHIVE["baseUrl"],
        "id": obj_id,
        "version": inv["head"],
        "inventorySha512": digest(d / inv["head"] / "inventory.json"),
        "follow": "latest",
        "cite": {"title": dc["titles"][0]["title"],
                 "creators": [display_name(c) for c in dc["creators"]],
                 "year": dc["publicationYear"]},
    } for obj_id, d, inv, prov, dc in docs]
    coll_dir = OCFL / coll_id
    inv = load_inventory(coll_dir)
    version = 1
    if inv:
        old = json.loads(read_logical(coll_dir, inv, "members.json").read_text())
        if old["members"] == members:
            print(f"{coll_id}: unchanged ({inv['head']})")
            return
        version = json.loads(read_logical(coll_dir, inv, "provenance.json").read_text())["documentVersion"] + 1
    today = datetime.date.today().isoformat()
    cur = ARCHIVE["curator"]
    tmp = Path(tempfile.mkdtemp())
    write_json(tmp / "members.json", {"format": "opensheaf-collection/0.1", "members": members})
    write_json(tmp / "datacite.json", {
        "titles": [{"title": ARCHIVE["name"]}],
        "creators": [{"name": cur["name"], "nameType": "Personal", "givenName": cur["givenName"],
                      "familyName": cur["familyName"], "affiliation": [{"name": cur["affiliation"]}]}],
        "publisher": {"name": ARCHIVE["name"]},
        "publicationYear": int(today[:4]),
        "types": {"resourceTypeGeneral": "Collection"},
        "version": str(version),
        "url": ARCHIVE["baseUrl"],
        "dates": [{"date": today, "dateType": "Available"}],
        "descriptions": [{"description": "The documents deposited in this archive, newest first.",
                          "descriptionType": "Abstract"}],
        "rightsList": [{"rights": "Creative Commons Zero v1.0 Universal",
                        "rightsUri": "https://creativecommons.org/publicdomain/zero/1.0/",
                        "rightsIdentifier": "cc0-1.0", "rightsIdentifierScheme": "SPDX"}],
    })
    write_json(tmp / "provenance.json", {
        "format": "opensheaf-provenance/0.1", "specification": SPEC, "kind": "collection",
        "archiveId": ARCHIVE["archiveId"], "objectId": coll_id, "documentVersion": version,
        "deposit": {"date": now(), "agent": {"name": ARCHIVE["depositor"]["name"],
                                             "uri": ARCHIVE["depositor"]["address"]}},
        "status": "active",
    })
    inv = add_version(coll_id, {n: tmp / n for n in ("members.json", "datacite.json", "provenance.json")},
                      f"Collection version {version}: {len(members)} documents")
    shutil.rmtree(tmp, ignore_errors=True)
    print(f"{coll_id}: {inv['head']} ({len(members)} members)")


