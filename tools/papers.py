#!/usr/bin/env python3
"""Keep the papers archive as an OpenSheaf 0.1 archive.

The archive (https://opensheaf.org, specification 0.1):

    opensheaf.json                discovery document (generated by `index`)
    ocfl/                         OCFL 1.1 storage root, flat-direct layout
      <id>/                       one object per document, and the collection
        v1/content/<id>.tm        sources (TeXmacs), paper.pdf,
        v1/content/datacite.json  datacite.json, provenance.json
        ...                       (collections: members.json)
    site/<id>/                    HTML version of each document (presentation)
    index-template.tm             surrounding text of the index
    index.tm, index.html          the index, generated from the main collection
    notes-meta.ts, paper-html.ts  style packages of the pages; resources/

Commands:

    papers.py deposit ID SOURCE.tm --title T --author "Family, Given|Affiliation" ...
        [--date YYYY-MM-DD] [--related arxiv=ID] [--rights TEXT]
        [--extra-source FILE[=LOGICAL/PATH] ...]  (other sources, e.g. a .bib
        file, at the path the main source refers to)
        Deposit a document, or a new version of it: the source is copied byte
        for byte, the PDF is typeset from a copy (bibliographies and tables
        are not regenerated), datacite.json and provenance.json are written,
        and the object gets a new OCFL version. The HTML version is exported
        to site/ID/ (not part of the deposit).
    papers.py collect     new version of the main collection if any document
                          has a new head version
    papers.py index       write opensheaf.json, index.tm and the HTML pages
    papers.py verify      check the archive (sections 5 to 14 of the
                          specification; JSON Schemas and the OCFL validator
                          ocfl-py are used when installed)

TeXmacs runs headless with a private profile in texmacs_home/ (not
committed), using the notes and max-html plugins linked in ~/.TeXmacs/plugins.
"""

